#!/usr/bin/env node
/**
 * ChromaDB Setup Script
 * Indexes knowledge base documents into ChromaDB for RAG queries
 * 
 * Usage: node scripts/setup-chromadb.js
 * 
 * Prerequisites:
 * - pip install chromadb
 * - Knowledge base documents in knowledge-base/
 */

import { readdir, readFile, stat, mkdir } from 'fs/promises';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const KNOWLEDGE_BASE_PATH = join(__dirname, '../knowledge-base');
const CHROMA_DB_PATH = join(__dirname, '../data/chroma-db');

/**
 * Check if ChromaDB is installed
 */
function checkChromaDB() {
    try {
        execSync('python3 -c "import chromadb"', { stdio: 'ignore' });
        return true;
    } catch {
        return false;
    }
}

/**
 * Install ChromaDB if not present
 */
function installChromaDB() {
    console.log('Installing ChromaDB...');
    try {
        execSync('pip3 install chromadb', { stdio: 'inherit' });
        return true;
    } catch (error) {
        console.error('Failed to install ChromaDB:', error.message);
        return false;
    }
}

/**
 * Load all documents from knowledge base
 */
async function loadDocuments() {
    const documents = [];
    
    async function scanDirectory(dirPath, category = '') {
        const entries = await readdir(dirPath);
        
        for (const entry of entries) {
            const fullPath = join(dirPath, entry);
            const stats = await stat(fullPath);
            
            if (stats.isDirectory()) {
                await scanDirectory(fullPath, entry);
            } else if (entry.endsWith('.md') || entry.endsWith('.json')) {
                const content = await readFile(fullPath, 'utf8');
                documents.push({
                    id: `${category}/${entry}`.replace(/^\//, ''),
                    category,
                    filename: entry,
                    content,
                    path: fullPath
                });
            }
        }
    }
    
    await scanDirectory(KNOWLEDGE_BASE_PATH);
    return documents;
}

/**
 * Split document into chunks for embedding
 */
function chunkDocument(doc, chunkSize = 500, overlap = 50) {
    const chunks = [];
    const words = doc.content.split(/\s+/);
    
    for (let i = 0; i < words.length; i += chunkSize - overlap) {
        const chunk = words.slice(i, i + chunkSize).join(' ');
        if (chunk.trim()) {
            chunks.push({
                id: `${doc.id}_chunk_${chunks.length}`,
                text: chunk,
                metadata: {
                    source: doc.id,
                    category: doc.category,
                    filename: doc.filename,
                    chunkIndex: chunks.length
                }
            });
        }
    }
    
    return chunks;
}

/**
 * Create Python script for ChromaDB indexing
 */
function createIndexingScript(chunks) {
    const chunksJson = JSON.stringify(chunks, null, 2);
    
    return `#!/usr/bin/env python3
"""
ChromaDB Indexing Script
Auto-generated by setup-chromadb.js
"""

import chromadb
from chromadb.config import Settings
import json

# Initialize ChromaDB
client = chromadb.PersistentClient(path="${CHROMA_DB_PATH}")

# Create or get collection
collection = client.get_or_create_collection(
    name="evony_knowledge",
    metadata={"description": "Evony game knowledge base"}
)

# Document chunks
chunks = ${chunksJson}

# Index documents
print(f"Indexing {len(chunks)} chunks...")

ids = [chunk['id'] for chunk in chunks]
documents = [chunk['text'] for chunk in chunks]
metadatas = [chunk['metadata'] for chunk in chunks]

# Add to collection (will use default embedding function)
collection.add(
    ids=ids,
    documents=documents,
    metadatas=metadatas
)

print(f"Successfully indexed {len(chunks)} chunks into ChromaDB")
print(f"Database location: ${CHROMA_DB_PATH}")

# Verify
count = collection.count()
print(f"Total documents in collection: {count}")
`;
}

/**
 * Main setup function
 */
async function main() {
    console.log('=== ChromaDB Setup for Evony Knowledge Base ===\n');
    
    // Check/install ChromaDB
    if (!checkChromaDB()) {
        console.log('ChromaDB not found, attempting installation...');
        if (!installChromaDB()) {
            console.error('Please install ChromaDB manually: pip install chromadb');
            process.exit(1);
        }
    }
    console.log('✓ ChromaDB is available\n');
    
    // Ensure directories exist
    try {
        await mkdir(CHROMA_DB_PATH, { recursive: true });
    } catch (e) {
        // Directory exists
    }
    
    // Load documents
    console.log('Loading knowledge base documents...');
    const documents = await loadDocuments();
    console.log(`✓ Found ${documents.length} documents\n`);
    
    if (documents.length === 0) {
        console.log('No documents found in knowledge-base/');
        console.log('Please add markdown or JSON files to the knowledge-base directory.');
        process.exit(1);
    }
    
    // Chunk documents
    console.log('Chunking documents for embedding...');
    const allChunks = [];
    for (const doc of documents) {
        const chunks = chunkDocument(doc);
        allChunks.push(...chunks);
    }
    console.log(`✓ Created ${allChunks.length} chunks\n`);
    
    // Create and run indexing script
    console.log('Creating indexing script...');
    const scriptContent = createIndexingScript(allChunks);
    const scriptPath = join(__dirname, 'index-chromadb.py');
    
    const { writeFile } = await import('fs/promises');
    await writeFile(scriptPath, scriptContent);
    console.log(`✓ Script written to ${scriptPath}\n`);
    
    // Run the Python script
    console.log('Running ChromaDB indexing...');
    try {
        execSync(`python3 ${scriptPath}`, { stdio: 'inherit' });
        console.log('\n✓ ChromaDB setup complete!');
    } catch (error) {
        console.error('Indexing failed:', error.message);
        console.log('\nYou can run the indexing manually:');
        console.log(`  python3 ${scriptPath}`);
    }
}

main().catch(error => {
    console.error('Setup failed:', error);
    process.exit(1);
});
